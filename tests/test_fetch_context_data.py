SPEC.loader.exec_module(F)

MON = ["January", "February", "March", "April", "May", "June", "July", "August", "September", "October", "November", "December"]


def fx_fomc(y):                      # 8 fixture meetings: second Tuesday-Wednesday of these months
    out = []
    for m in (1, 3, 5, 6, 7, 9, 11, 12):
        d = dt.date(y, m, 1)
        d += dt.timedelta(days=(1 - d.weekday()) % 7 + 7)
        out.append((d, d + dt.timedelta(days=1)))
    return out


def fomc_calendar_html(years):
    h = ["<html><body>"]
    for y in years:
        h.append(f'<div class="panel"><div class="panel-heading"><h4>{y} FOMC Meetings</h4></div>')
        for a, b in fx_fomc(y):
            h.append(f'<div class="row fomc-meeting"><div class="fomc-meeting__month"><strong>{MON[a.month - 1]}</strong></div>'
                     f'<div class="fomc-meeting__date">{a.day}-{b.day}</div></div>')
            h.append(f"<div>Minutes: Released {MON[b.month - 1]} {b.day + 1}, {y}</div>")      # must not be read as a meeting
        # an unscheduled call and a notation vote
        h.append('<div class="row"><div class="fomc-meeting__month"><strong>March</strong></div><div class="fomc-meeting__date">15</div><div>(unscheduled)</div></div>')
        h.append('<div class="row"><div class="fomc-meeting__month"><strong>October</strong></div><div class="fomc-meeting__date">4</div><div>(notation vote)</div></div>')
        h.append("</div>")
    return "".join(h) + "</body></html>"


def bls_month_html(y, m, skip=()):
    d0 = dt.date(y, m, 1)
    cpi = d0 + dt.timedelta(days=11)
    while cpi.weekday() >= 5:
        cpi += dt.timedelta(days=1)
    ppi = cpi + dt.timedelta(days=1)
    while ppi.weekday() >= 5:
        ppi += dt.timedelta(days=1)
    nfp = d0 + dt.timedelta(days=(4 - d0.weekday()) % 7)             # first Friday
    rows = [(nfp, "Employment Situation"), (cpi, "Consumer Price Index"), (ppi, "Producer Price Index"),
            (cpi, "Real Earnings"), (ppi, "Import and Export Prices"), (nfp, "State Employment and Unemployment"),
            (nfp, "Employment Cost Index")]
    rows = [r for r in rows if r[1] not in skip]
    return "<table>" + "".join(
        f"<tr><td>{d.strftime('%A')}, {MON[d.month - 1][:3]}. {d.day}, {d.year}</td><td>08:30 AM</td><td>{n}</td></tr>" for d, n in sorted(rows)) + "</table>"


def fred_csv(y0, y1, series="DFF", last=None, hole=None):
    d = dt.date(y0, 1, 1)
    end = last or dt.date(y1, 12, 31)
    out = [f"observation_date,{series}"]
    while d <= end:
        if hole is None or not (hole[0] <= d <= hole[1]):
            out.append(f"{d},{'.' if d.day == 5 else format(0.25 + 0.001 * (d.year - y0), 'g')}")
        d += dt.timedelta(days=1)
    return "\n".join(out) + "\n"


def make_fetch(y0=2016, y1=2026, skip_month=None, fomc_years=None, **fred_kw):
    pages = {F.FOMC_CAL_URL: fomc_calendar_html(fomc_years or range(y0, y1 + 1))}
    for y in range(y0, y1 + 1):
        for m in range(1, 13):
            pages[F.BLS_MONTH_URL.format(year=y, month=m)] = bls_month_html(y, m, skip=("Consumer Price Index",) if skip_month == (y, m) else ())
    pages[F.FRED_URL.format(series="DFF", start=f"{y0}-01-01", end=f"{y1}-12-31")] = fred_csv(y0, y1, **fred_kw)

    def fetch(url):
        if url in pages:
            return pages[url]
        raise F.FetchError(f"404 {url}")
    return fetch


TODAY = dt.date(2026, 12, 31)


# ------------------------------------------------------------------ parsers
def test_fomc_parser_takes_scheduled_decision_days_only():
    got = F.parse_fomc(fomc_calendar_html([2019]))
    assert set(got) == {b for a, b in fx_fomc(2019)}
    assert dt.date(2019, 3, 15) not in got and dt.date(2019, 10, 4) not in got      # unscheduled / notation vote


def test_fomc_cross_month_meeting_uses_the_second_month():
    page = ('<div>2019 FOMC Meetings</div><div class="m"><strong>Jan/Feb</strong></div><div class="d">31-1</div>'
            '<div class="m"><strong>Apr/May</strong></div><div class="d">30-1</div>')
    assert F.parse_fomc(page) == [dt.date(2019, 2, 1), dt.date(2019, 5, 1)]


def test_fomc_historical_heading_format():
    page = "<h5>January 26-27 Meeting - 2016</h5><h5>April 26-27 Meeting - 2016</h5><h5>Conference Call - March 3, 2016</h5><h5>Unscheduled Meeting</h5>"
    assert F.parse_fomc(page, 2016) == [dt.date(2016, 1, 27), dt.date(2016, 4, 27)]


def test_bls_month_parser_picks_only_the_three_releases():
    got = F.parse_bls_month(bls_month_html(2019, 3), 2019, 3)
    assert set(got) == {"CPI", "PPI", "NFP"} and all(len(v) == 1 for v in got.values())
    assert got["NFP"][0] == dt.date(2019, 3, 1) and got["CPI"][0].weekday() < 5


