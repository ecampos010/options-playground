def test_fomc_count_and_duplicates_and_sort_and_weekend_checks():
    d = dt.date
    base = [(d(2020, 1, 6), "FOMC", "")] * 8
    with pytest.raises(F.SanityError, match="duplicate"):
        F.check_events(base, 2020, 2020, {})
    few = [(d(2020, m, 3), "FOMC", "") for m in (1, 3, 5)]
    with pytest.raises(F.SanityError, match="2020: 3 FOMC"):
        F.check_events(few, 2020, 2020, {})
    with pytest.raises(F.SanityError, match="not sorted"):
        F.check_events([(d(2020, 3, 3), "FOMC", ""), (d(2020, 1, 7), "FOMC", "")], 2020, 2020, {})
    with pytest.raises(F.SanityError, match="weekend"):
        F.check_events([(d(2020, 1, 4), "CPI", "")], 2020, 2020, {})
    with pytest.raises(F.SanityError, match="unknown event type"):
        F.check_events([(d(2020, 1, 6), "FOO", "")], 2020, 2020, {})


def test_rates_checks_gap_stale_range_and_units():
    d = dt.date
    ok = [(d(2020, 1, 1) + dt.timedelta(days=i), 1.5) for i in range(40)]
    F.check_rates(ok, 2020, d(2020, 2, 10))
    with pytest.raises(F.SanityError, match="gaps longer"):
        F.check_rates(ok[:10] + ok[25:], 2020, d(2020, 2, 10))
    with pytest.raises(F.SanityError, match="days old"):
        F.check_rates(ok, 2020, d(2020, 6, 1))
    with pytest.raises(F.SanityError, match="outside 0-25"):
        F.check_rates([(d(2020, 1, 1), 150.0)], 2020, d(2020, 1, 2))
    with pytest.raises(F.SanityError, match="not sorted|duplicate"):
        F.check_rates([ok[1], ok[0]] + ok[2:], 2020, d(2020, 2, 10))



