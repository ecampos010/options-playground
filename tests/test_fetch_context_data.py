def test_fred_parser_skips_missing_and_checks_header():
    rows = F.parse_fred("observation_date,DFF\n2020-01-01,1.55\n2020-01-02,.\n2020-01-03,1.56\n", "DFF")
    assert rows == [(dt.date(2020, 1, 1), 1.55), (dt.date(2020, 1, 3), 1.56)]
